"""Field-level evaluation of the schema-constrained rule-based extractor.

Evaluates the open, deterministic rule-based extractor (redflag_benchmark.
extract_features) against the gold structured features of the text benchmark, at
the field level. This is the reproducible BASELINE against which an open medical
LLM (e.g., MedGemma) will be benchmarked once model + clinical-text access are
available; the harness (metrics + gold) is fixed here so that comparison is
prespecified.

Per safety-relevant feature we report detection precision/recall/F1 (positive
class = feature present) and accuracy; we also report macro-averages, document-
level exact feature match, the urgency-changing (clinically significant) error
rate, and run-to-run consistency (1.00 for a deterministic extractor).

Run:
    python src/run_extraction_eval.py \
        --out ../paper02/outputs/extraction_eval.json \
        --latex ../paper02/tables/table_extraction.tex
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

from redflag_benchmark import TEXT_CASES, extract_features, FEATURE_KEYS
from safety import evaluate_red_flags
from llm_eval import document_exact_match, run_consistency


def _feature_metrics(gold, pred):
    """Per-feature detection metrics (positive class = feature True)."""
    out = {}
    macro = {"precision": [], "recall": [], "f1": [], "accuracy": []}
    for f in FEATURE_KEYS:
        tp = fp = fn = tn = 0
        for g, p in zip(gold, pred):
            gv, pv = bool(g.get(f, False)), bool(p.get(f, False))
            if gv and pv:
                tp += 1
            elif not gv and pv:
                fp += 1
            elif gv and not pv:
                fn += 1
            else:
                tn += 1
        prec = tp / (tp + fp) if (tp + fp) else float("nan")
        rec = tp / (tp + fn) if (tp + fn) else float("nan")
        f1 = (2 * prec * rec / (prec + rec)
              if prec == prec and rec == rec and (prec + rec) else float("nan"))
        acc = (tp + tn) / (tp + fp + fn + tn)
        out[f] = {"precision": prec, "recall": rec, "f1": f1, "accuracy": acc,
                  "support": tp + fn}
        for k, v in (("precision", prec), ("recall", rec), ("f1", f1), ("accuracy", acc)):
            if v == v:
                macro[k].append(v)
    macro = {k: (sum(v) / len(v) if v else float("nan")) for k, v in macro.items()}
    return out, macro


def evaluate():
    gold = [c.gold_features for c in TEXT_CASES]
    pred = [extract_features(c.note) for c in TEXT_CASES]
    per_feat, macro = _feature_metrics(gold, pred)

    # Urgency-changing (clinically significant) error: extraction flips the
    # deterministic layer's decision relative to the gold features.
    flips = 0
    for c, p in zip(TEXT_CASES, pred):
        gold_urgent = evaluate_red_flags(c.gold_features).urgent
        pred_urgent = evaluate_red_flags(p).urgent
        if gold_urgent != pred_urgent:
            flips += 1
    return {
        "n_docs": len(TEXT_CASES),
        "per_feature": per_feat,
        "macro": macro,
        "document_exact_feature_match": document_exact_match(gold, pred, FEATURE_KEYS),
        "clinically_significant_error_rate": flips / len(TEXT_CASES),
        "run_consistency": run_consistency([pred, pred], FEATURE_KEYS),
    }


def to_latex(res):
    def num(x):
        return "--" if x != x else f"{x:.2f}"
    lines = [
        "\\begin{table}[htbp]", "\\centering",
        "\\caption{\\textbf{Schema-constrained rule-based extraction baseline} on "
        f"the {res['n_docs']}-note benchmark (gold structured features). Detection "
        "precision/recall/F1 per safety-relevant feature (positive class = feature "
        "present). This open, deterministic baseline is the prespecified reference "
        "for a future open-LLM (e.g., MedGemma) comparison. Generated by "
        "\\texttt{code/src/run\\_extraction\\_eval.py}.}",
        "\\label{tab:extraction}", "\\small",
        "\\begin{tabular}{lcccc}", "\\toprule",
        "Feature & Prec. & Rec. & F1 & Support \\\\", "\\midrule",
    ]
    label = {
        "sudden_hearing_loss": "Sudden hearing loss",
        "rapidly_progressive_loss": "Rapidly progressive loss",
        "unilateral_sudden_symptom": "Unilateral acute symptom",
        "aural_fullness_acute_onset": "Acute aural fullness",
        "single_sided_tinnitus": "Single-sided tinnitus",
        "asymmetric_hearing": "Asymmetric hearing",
        "vertigo": "Vertigo",
        "focal_neurologic_sign": "Focal neurologic sign",
    }
    for f in FEATURE_KEYS:
        m = res["per_feature"][f]
        lines.append(f"{label[f]} & {num(m['precision'])} & {num(m['recall'])} & "
                     f"{num(m['f1'])} & {m['support']} \\\\")
    ma = res["macro"]
    lines += [
        "\\midrule",
        f"\\textbf{{Macro average}} & {num(ma['precision'])} & {num(ma['recall'])} "
        f"& {num(ma['f1'])} & \\\\",
        "\\bottomrule", "\\end{tabular}",
        "\\vspace{2pt}",
        "{\\footnotesize Document-level exact feature match: "
        f"{num(res['document_exact_feature_match'])}; urgency-changing error rate: "
        f"{num(res['clinically_significant_error_rate'])}; run-to-run consistency: "
        f"{num(res['run_consistency'])} (deterministic).}}",
        "\\end{table}", "",
    ]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="../paper02/outputs/extraction_eval.json")
    ap.add_argument("--latex", default="../paper02/tables/table_extraction.tex")
    args = ap.parse_args()
    res = evaluate()
    Path(args.out).parent.mkdir(parents=True, exist_ok=True)
    Path(args.out).write_text(json.dumps(res, indent=2), encoding="utf-8")
    Path(args.latex).parent.mkdir(parents=True, exist_ok=True)
    Path(args.latex).write_text(to_latex(res), encoding="utf-8")
    print(f"Wrote {args.out} and {args.latex}")
    print(f"macro F1={res['macro']['f1']:.2f}  doc-exact="
          f"{res['document_exact_feature_match']:.2f}  "
          f"urgency-changing-error={res['clinically_significant_error_rate']:.2f}")


if __name__ == "__main__":
    main()
