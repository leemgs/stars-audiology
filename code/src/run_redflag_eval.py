"""Evaluate the deterministic referral-safety layer on the open benchmark.

Produces the real results for the companion (paper B) study at two levels:

  1. STRUCTURED (rule coverage): the layer on correctly-extracted features vs.
     the a-priori guideline urgency label.
  2. END-TO-END (text -> rule-based extraction -> layer): recall/specificity
     bounded by extraction, with a per-category breakdown that isolates where
     adversarial phrasing (negation/colloquial/ambiguous) creates risk.

Outputs a results JSON and LaTeX tables the paper02 manuscript \\input's.

Run:
    python src/run_redflag_eval.py \
        --out ../paper02/outputs/redflag_eval.json \
        --latex-dir ../paper02/tables
"""
from __future__ import annotations

import argparse
import json
from math import sqrt
from pathlib import Path

from safety import evaluate_red_flags
from redflag_benchmark import STRUCTURED, TEXT_CASES, EXTRACTORS, benchmark_summary


def wilson(k: int, n: int, z: float = 1.96):
    """Wilson score 95% CI for a proportion (robust at 0/1 and small n)."""
    if n == 0:
        return (float("nan"), float("nan"), float("nan"))
    p = k / n
    denom = 1 + z * z / n
    centre = (p + z * z / (2 * n)) / denom
    half = (z * sqrt(p * (1 - p) / n + z * z / (4 * n * n))) / denom
    return (p, max(0.0, centre - half), min(1.0, centre + half))


def _confusion(pairs):
    """pairs: iterable of (gold_urgent, pred_urgent) -> tp, fp, tn, fn."""
    tp = fp = tn = fn = 0
    for gold, pred in pairs:
        if gold and pred:
            tp += 1
        elif gold and not pred:
            fn += 1
        elif not gold and pred:
            fp += 1
        else:
            tn += 1
    return tp, fp, tn, fn


def _metrics(tp, fp, tn, fn):
    sens = wilson(tp, tp + fn)
    spec = wilson(tn, tn + fp)
    over = wilson(fp, fp + tn)   # over-referral among true negatives
    return {
        "tp": tp, "fp": fp, "tn": tn, "fn": fn,
        "sensitivity": sens[0], "sensitivity_ci": [sens[1], sens[2]],
        "specificity": spec[0], "specificity_ci": [spec[1], spec[2]],
        "over_referral": over[0], "over_referral_ci": [over[1], over[2]],
    }


def structured_eval():
    pairs = [(s.gold_urgent, evaluate_red_flags(s.features).urgent) for s in STRUCTURED]
    res = _metrics(*_confusion(pairs))
    # subgroup recall by onset (positives only)
    res["subgroup_recall"] = {}
    for onset in ("acute", "gradual"):
        pos = [s for s in STRUCTURED if s.gold_urgent and s.onset == onset]
        hit = sum(evaluate_red_flags(s.features).urgent for s in pos)
        if pos:
            res["subgroup_recall"][onset] = {"hit": hit, "n": len(pos)}
    return res


def end_to_end_eval(extractor):
    pairs = [(c.gold_urgent, evaluate_red_flags(extractor(c.note)).urgent)
             for c in TEXT_CASES]
    res = _metrics(*_confusion(pairs))
    res["by_category"] = {}
    for cat in sorted({c.category for c in TEXT_CASES}):
        cp = [(c.gold_urgent, evaluate_red_flags(extractor(c.note)).urgent)
              for c in TEXT_CASES if c.category == cat]
        res["by_category"][cat] = _metrics(*_confusion(cp))
    return res


def _fmt_pct(p):
    return "--" if p != p else f"{100*p:.0f}\\%"


def _fmt_ci(m):
    lo, hi = m
    if lo != lo:
        return "--"
    return f"({100*lo:.0f}--{100*hi:.0f})"


_EXTRACTOR_LABEL = {
    "rule_v1": "End-to-end, rule-based v1",
    "rule_v2": "End-to-end, rule-based v2 (improved)",
}


def to_latex(struct, e2e_by, summ):
    def row(label, r):
        return (f"{label} & {r['tp']+r['fn']} & {r['tn']+r['fp']} & "
                f"{_fmt_pct(r['sensitivity'])} {_fmt_ci(r['sensitivity_ci'])} & "
                f"{_fmt_pct(r['specificity'])} {_fmt_ci(r['specificity_ci'])} & "
                f"{_fmt_pct(r['over_referral'])} \\\\")
    main = [
        "\\begin{table}[htbp]", "\\centering",
        "\\caption{\\textbf{Deterministic referral-safety layer on the open "
        f"benchmark}} ({summ['n_structured']} structured + {summ['n_text']} "
        "text cases; expert-authored/synthetic, no patient data). Sensitivity is "
        "red-flag recall (the safety-critical metric); 95\\% Wilson CIs. "
        "\\emph{Structured} evaluates rule coverage on correctly-extracted "
        "features; \\emph{end-to-end} runs free text through a rule-based "
        "extractor first, so the benchmark discriminates extractor quality "
        "(v1 vs.\\ the improved v2). Generated by "
        "\\texttt{code/src/run\\_redflag\\_eval.py}.}",
        "\\label{tab:redflag_results}", "\\small",
        "\\begin{tabular}{lccccc}", "\\toprule",
        "Evaluation & Pos. & Neg. & Sensitivity (95\\% CI) & Specificity (95\\% CI) "
        "& Over-referral \\\\", "\\midrule",
        row("Structured (rule coverage)", struct),
    ]
    for name, r in e2e_by.items():
        main.append(row(_EXTRACTOR_LABEL.get(name, name), r))
    main += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]

    # end-to-end sensitivity by category, per extractor (comparison)
    cats = sorted({c for r in e2e_by.values() for c in r["by_category"]})
    names = list(e2e_by.keys())
    header = "Note category & " + " & ".join(
        f"{_EXTRACTOR_LABEL.get(n, n).split(',')[-1].strip()}" for n in names) + " \\\\"
    cat = [
        "\\begin{table}[htbp]", "\\centering",
        "\\caption{\\textbf{End-to-end red-flag recall by note category and "
        "extractor.} Adversarial phrasing (colloquial, ambiguous, historical) is "
        "where extraction error --- not the deterministic rules --- creates "
        "residual risk; the improved extractor (v2) recovers most of it, "
        "quantifying the benchmark's discriminative value. `--' = no positive "
        "case in that cell. Generated by "
        "\\texttt{code/src/run\\_redflag\\_eval.py}.}",
        "\\label{tab:redflag_bycat}", "\\small",
        f"\\begin{{tabular}}{{l{'c'*len(names)}}}", "\\toprule",
        header, "\\midrule",
    ]
    for c in cats:
        cells = " & ".join(_fmt_pct(e2e_by[n]["by_category"].get(c, {}).get(
            "sensitivity", float("nan"))) for n in names)
        cat.append(f"{c} & {cells} \\\\")
    cat += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    return "\n".join(main), "\n".join(cat)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="../paper02/outputs/redflag_eval.json")
    ap.add_argument("--latex-dir", default="../paper02/tables")
    args = ap.parse_args()

    summ = benchmark_summary()
    struct = structured_eval()
    e2e_by = {name: end_to_end_eval(fn) for name, fn in EXTRACTORS.items()}
    res = {"benchmark": summ, "structured": struct, "end_to_end": e2e_by}

    Path(args.out).parent.mkdir(parents=True, exist_ok=True)
    Path(args.out).write_text(json.dumps(res, indent=2), encoding="utf-8")
    print(f"Wrote {args.out}")

    t_main, t_cat = to_latex(struct, e2e_by, summ)
    ldir = Path(args.latex_dir)
    ldir.mkdir(parents=True, exist_ok=True)
    (ldir / "table_redflag_results.tex").write_text(t_main, encoding="utf-8")
    (ldir / "table_redflag_bycat.tex").write_text(t_cat, encoding="utf-8")
    print(f"Wrote {ldir}/table_redflag_results.tex and table_redflag_bycat.tex")

    print("\n== Summary ==")
    print(f"benchmark: {summ}")
    print(f"structured: sens={struct['sensitivity']:.2f} spec={struct['specificity']:.2f}")
    for name, r in e2e_by.items():
        print(f"end-to-end {name}: sens={r['sensitivity']:.2f} spec={r['specificity']:.2f}")


if __name__ == "__main__":
    main()
